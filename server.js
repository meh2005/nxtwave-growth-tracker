import express from "express";
import cors from "cors";
import { Pool } from "pg";
import { randomBytes, timingSafeEqual } from "node:crypto";
import { Buffer } from "node:buffer";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const app = express();
const PORT = Number(process.env.PORT) || 3001;
const HOST = "0.0.0.0";
const SERVER_DIR = dirname(fileURLToPath(import.meta.url));
const DIST_DIR = resolve(SERVER_DIR, "dist");
const DATABASE_URL = process.env.DATABASE_URL;

if (!DATABASE_URL) {
  throw new Error("DATABASE_URL must be configured before starting the server.");
}

const pool = new Pool({
  connectionString: DATABASE_URL,
  max: 5,
  connectionTimeoutMillis: 10000,
});

pool.on("error", (error) => {
  console.error("Unexpected PostgreSQL pool error:", error.code || "unknown");
});

app.use(cors());
app.use(express.json());

async function initializeSchema() {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query(`
      CREATE TABLE IF NOT EXISTS ambassadors (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        referral_code TEXT NOT NULL UNIQUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS registrations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL,
        college TEXT NOT NULL,
        channel TEXT NOT NULL,
        referral_code TEXT REFERENCES ambassadors(referral_code),
        verified BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

      ALTER TABLE registrations
        ADD COLUMN IF NOT EXISTS verified BOOLEAN NOT NULL DEFAULT FALSE;

      CREATE UNIQUE INDEX IF NOT EXISTS registrations_email_normalized
        ON registrations (LOWER(email));
    `);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

function logDatabaseError(error) {
  // Avoid logging query values, student data, DATABASE_URL, or ADMIN_SECRET.
  console.error("PostgreSQL operation failed:", error.code || "unknown");
}

function generateReferralCode() {
  return `AI-${randomBytes(4).toString("hex").toUpperCase()}`;
}

function requireAdmin(req, res, next) {
  const adminSecret = process.env.ADMIN_SECRET;
  if (!adminSecret) {
    return res.status(503).json({ error: "Organizer access is disabled until ADMIN_SECRET is configured." });
  }

  const suppliedSecret = Buffer.from(req.get("X-Admin-Secret") || "");
  const expectedSecret = Buffer.from(adminSecret);
  if (suppliedSecret.length !== expectedSecret.length || !timingSafeEqual(suppliedSecret, expectedSecret)) {
    return res.status(401).json({ error: "Invalid organizer secret." });
  }
  next();
}

app.get("/api/health", (req, res) => {
  res.json({ status: "ok", message: "Growth Tracker API is running" });
});

app.post("/api/ambassadors", requireAdmin, async (req, res) => {
  const name = String(req.body?.name || "").trim();
  if (!name) {
    return res.status(400).json({ error: "Ambassador name is required." });
  }

  for (let attempt = 0; attempt < 5; attempt++) {
    const code = generateReferralCode();
    try {
      const result = await pool.query(
        "INSERT INTO ambassadors (name, referral_code) VALUES ($1, $2) RETURNING id",
        [name, code],
      );
      return res.status(201).json({ id: result.rows[0].id, name, referralCode: code });
    } catch (error) {
      if (error.code === "23505") continue;
      logDatabaseError(error);
      return res.status(500).json({ error: "Could not create ambassador." });
    }
  }

  return res.status(500).json({ error: "Could not generate a unique code." });
});

app.get("/api/ambassadors", async (req, res) => {
  try {
    const result = await pool.query(`
      SELECT
        a.id,
        a.name,
        a.referral_code AS "referralCode",
        COUNT(r.id) FILTER (WHERE r.verified)::int AS registrations,
        COUNT(r.id)::int AS "totalRegistrations"
      FROM ambassadors a
      LEFT JOIN registrations r ON r.referral_code = a.referral_code
      GROUP BY a.id
      ORDER BY registrations DESC
    `);
    res.json(result.rows);
  } catch (error) {
    logDatabaseError(error);
    res.status(500).json({ error: "Could not load ambassadors." });
  }
});

app.post("/api/registrations", async (req, res) => {
  const body = req.body || {};
  const name = String(body.name || "").trim();
  const email = String(body.email || "").trim().toLowerCase();
  const college = String(body.college || "").trim();
  const channel = String(body.channel || "").trim();
  const referralCode = String(body.referralCode || "").trim().toUpperCase();

  if (!name || !email || !college || !channel) {
    return res.status(400).json({ error: "Name, email, college and channel are required." });
  }
  if (name.length > 100 || email.length > 254 || college.length > 160) {
    return res.status(400).json({ error: "Name, email, or college exceeds the allowed length." });
  }
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    return res.status(400).json({ error: "Enter a valid email address." });
  }

  const allowedChannels = ["WhatsApp", "College Club", "Instagram"];
  if (!allowedChannels.includes(channel)) {
    return res.status(400).json({ error: "Invalid campaign channel." });
  }

  try {
    if (referralCode) {
      const ambassador = await pool.query(
        "SELECT id FROM ambassadors WHERE referral_code = $1",
        [referralCode],
      );
      if (ambassador.rowCount === 0) {
        return res.status(400).json({ error: "Referral code not found." });
      }
    }

    const result = await pool.query(`
      INSERT INTO registrations (name, email, college, channel, referral_code)
      VALUES ($1, $2, $3, $4, $5)
      RETURNING id
    `, [name, email, college, channel, referralCode || null]);

    return res.status(201).json({
      id: result.rows[0].id,
      message: "Registration submitted. It will count toward rewards after verification.",
      verified: false,
    });
  } catch (error) {
    if (error.code === "23505") {
      return res.status(409).json({ error: "This email has already been registered." });
    }
    if (error.code === "23503") {
      return res.status(400).json({ error: "Referral code not found." });
    }
    logDatabaseError(error);
    return res.status(500).json({ error: "Could not save registration." });
  }
});

app.patch("/api/registrations/:id/verify", requireAdmin, async (req, res) => {
  const registrationId = Number(req.params.id);
  if (!Number.isSafeInteger(registrationId) || registrationId < 1) {
    return res.status(400).json({ error: "Invalid registration ID." });
  }

  try {
    const result = await pool.query(
      "UPDATE registrations SET verified = TRUE WHERE id = $1 RETURNING id",
      [registrationId],
    );
    if (result.rowCount === 0) {
      return res.status(404).json({ error: "Registration not found." });
    }
    return res.json({ message: "Registration verified." });
  } catch (error) {
    logDatabaseError(error);
    return res.status(500).json({ error: "Could not verify registration." });
  }
});

app.get("/api/registrations", requireAdmin, async (req, res) => {
  try {
    const result = await pool.query(`
      SELECT id, name, email, college, channel,
        referral_code AS "referralCode", verified, created_at AS "createdAt"
      FROM registrations
      ORDER BY id DESC
    `);
    res.json(result.rows);
  } catch (error) {
    logDatabaseError(error);
    res.status(500).json({ error: "Could not load registrations." });
  }
});

app.get("/api/stats", async (req, res) => {
  try {
    const totalsResult = await pool.query(`
      SELECT
        COUNT(*) FILTER (WHERE verified)::int AS total,
        COUNT(*) FILTER (WHERE NOT verified)::int AS pending,
        COUNT(*) FILTER (WHERE verified AND referral_code IS NOT NULL)::int AS referred
      FROM registrations
    `);
    const channelsResult = await pool.query(`
      SELECT channel, COUNT(*)::int AS registrations
      FROM registrations
      WHERE verified = TRUE
      GROUP BY channel
    `);
    const { total, pending, referred } = totalsResult.rows[0];

    res.json({
      target: 500,
      total,
      pending,
      referred,
      progress: Math.round((total / 500) * 100),
      channels: channelsResult.rows,
    });
  } catch (error) {
    logDatabaseError(error);
    res.status(500).json({ error: "Could not load campaign statistics." });
  }
});

app.use("/api", (req, res) => {
  res.status(404).json({ error: "API route not found." });
});

if (process.env.NODE_ENV === "production") {
  app.use(express.static(DIST_DIR));
  app.get("/{*path}", (req, res) => res.sendFile(resolve(DIST_DIR, "index.html")));
}

await initializeSchema();

const server = app.listen(PORT, HOST, () => {
  console.log(`Growth Tracker server listening on ${HOST}:${PORT}`);
  console.log("PostgreSQL connection pool ready.");
});

process.on("SIGTERM", () => {
  server.close(async () => {
    await pool.end();
    process.exit(0);
  });
});
